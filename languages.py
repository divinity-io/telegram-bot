def get_text(key, language="English", **kwargs):

    language_data = LANGUAGES.get(
        language,
        LANGUAGES["English"]
    )

    text = language_data.get(
        key,
        LANGUAGES["English"].get(key, key)
    )

    return text.format(**kwargs)
